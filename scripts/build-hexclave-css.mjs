// Generates src/app/hexclave-theme.css from the installed @hexclave/next.
// HexclaveTheme normally injects this CSS at runtime, but it also runs eval(),
// which the production CSP blocks. Rendering it once here keeps the SDK's own
// styles (and their spinner/visibility rules) without loosening the CSP.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

// The SDK's ESM build imports "next/navigation" without an extension, which plain Node rejects.
const { HexclaveTheme } = createRequire(import.meta.url)("@hexclave/next");
const html = renderToStaticMarkup(createElement(HexclaveTheme, null, null));
const match = html.match(/<style[^>]*>([\s\S]*?)<\/style>/);
if (!match) {
  console.error("build-hexclave-css: no <style> found in HexclaveTheme output");
  process.exit(1);
}
const out = new URL("../src/app/hexclave-theme.css", import.meta.url);
writeFileSync(out, "/* Generated by scripts/build-hexclave-css.mjs from @hexclave/next. Do not edit. */\n" + match[1] + "\n");
console.log("build-hexclave-css: wrote", out.pathname, match[1].length, "chars");
